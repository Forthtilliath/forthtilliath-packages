// Scopes every shadcn-ui colour theme under `:root[data-palette="<name>"]`
// into app/palette/palettes.css, so the palette can be switched at runtime
// (see app/palette/). Run by predev / prebuild; the output is not committed.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const appDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const themesDir = join(
  appDir,
  "node_modules/@forthtilliath/shadcn-ui/src/styles/themes",
);
const listFile = join(appDir, "app/palette/palettes.ts");
const outFile = join(appDir, "app/palette/palettes.css");

/** Top-level `{ prelude, body }` blocks of `css` (comments removed first). */
function parseBlocks(css) {
  const source = css.replace(/\/\*[\s\S]*?\*\//g, "");
  const blocks = [];
  let depth = 0;
  let start = 0;
  let open = 0;
  for (let i = 0; i < source.length; i++) {
    if (source[i] === "{") {
      if (depth === 0) open = i;
      depth++;
    } else if (source[i] === "}") {
      depth--;
      if (depth === 0) {
        blocks.push({
          prelude: source.slice(start, open).trim(),
          body: source.slice(open + 1, i),
        });
        start = i + 1;
      }
    }
  }
  return blocks;
}

/** Splits a selector list on its top-level commas. */
function splitSelectors(prelude) {
  const parts = [];
  let depth = 0;
  let start = 0;
  for (let i = 0; i < prelude.length; i++) {
    const c = prelude[i];
    if (c === "(" || c === "[") depth++;
    else if (c === ")" || c === "]") depth--;
    else if (c === "," && depth === 0) {
      parts.push(prelude.slice(start, i).trim());
      start = i + 1;
    }
  }
  parts.push(prelude.slice(start).trim());
  return parts;
}

function scopeSelector(selector, scope, theme) {
  let head = `${scope} `;
  let tail = selector;
  if (selector.startsWith(":root")) [head, tail] = [scope, selector.slice(5)];
  else if (selector.startsWith(".dark"))
    [head, tail] = [`${scope}.dark`, selector.slice(5)];
  else if (/^html\b/.test(selector)) [head, tail] = [scope, selector.slice(4)];
  // `:root` / `.dark` / `html` anywhere else would be scoped wrongly.
  if (/:root|\.dark\b|(^|[\s>+~(])html\b/.test(tail)) {
    throw new Error(`${theme}.css: unsupported selector "${selector}"`);
  }
  return head + tail;
}

function scopeCss(css, scope, theme) {
  return parseBlocks(css)
    .map(({ prelude, body }) => {
      if (/^@(media|supports|container)\b/.test(prelude)) {
        return `${prelude} {\n${scopeCss(body, scope, theme)}\n}`;
      }
      // @keyframes, @font-face…: global, kept as is.
      if (prelude.startsWith("@")) return `${prelude} {${body}}`;
      const selectors = splitSelectors(prelude).map((s) =>
        scopeSelector(s, scope, theme),
      );
      return `${selectors.join(",\n")} {${body}}`;
    })
    .join("\n\n");
}

const themes = readdirSync(themesDir)
  .filter((file) => file.endsWith(".css"))
  .map((file) => basename(file, ".css"))
  .sort();

// The selector's list (palettes.ts) must match the themes folder exactly.
const listed = [
  ...readFileSync(listFile, "utf8")
    .match(/PALETTES = \[([\s\S]*?)\]/)[1]
    .matchAll(/"([^"]+)"/g),
].map((m) => m[1]);
const missing = themes.filter((t) => !listed.includes(t));
const unknown = listed.filter((t) => !themes.includes(t));
if (missing.length || unknown.length) {
  throw new Error(
    `app/palette/palettes.ts is out of date — missing: [${missing.join(", ")}], unknown: [${unknown.join(", ")}]`,
  );
}

const output = themes
  .map((theme) => {
    const css = readFileSync(join(themesDir, `${theme}.css`), "utf8");
    return `/* ${theme} */\n${scopeCss(css, `:root[data-palette="${theme}"]`, theme)}`;
  })
  .join("\n\n");

writeFileSync(
  outFile,
  `/* Generated by scripts/generate-palettes.mjs — do not edit. */\n\n${output}\n`,
);
console.log(`palettes.css: ${themes.length} palettes`);
