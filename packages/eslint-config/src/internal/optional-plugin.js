import { createRequire } from "node:module";

/**
 * Plugins that only some variants or options use are optional peer
 * dependencies (see package.json's `peerDependenciesMeta`): a React Native app
 * must not end up installing angular-eslint (and the whole Angular CLI it
 * pulls in), nor a plain TypeScript library every React plugin. Plugins a
 * variant always needs are imported statically by that variant's module;
 * plugins behind an option (`a11y`, `expo`, `i18n`, `testingLibrary`,
 * `turbo`) go through {@link requireOptional} instead, only when the option is
 * on, so a project that leaves it off doesn't have to install them.
 *
 * Loaded with `require()` rather than `import()`: an `await import()` at the
 * top of a variant module would make the whole package an async module, which
 * Node refuses to `require()` (`ERR_REQUIRE_ASYNC_MODULE`) — and the CommonJS
 * `eslint.config.js` generated by Expo's templates does exactly that.
 */
const require = createRequire(import.meta.url);

/**
 * Loads an optional plugin, or throws an error explaining which package to
 * install (or which option to turn off) when it isn't installed. Any other
 * failure (a broken install, a missing transitive dependency of the plugin
 * itself) is rethrown rather than hidden.
 *
 * Callers cast the result to the package's own type (its `import()`
 * default export) to keep the plugin's type, which `require()` loses.
 *
 * @param {string} name - The package name.
 * @param {string} option - The option that needs it, e.g. `a11y`.
 * @param {(name: string) => unknown} [load] - Stands in for `require` in tests.
 * @returns {unknown}
 */
export function requireOptional(name, option, load = require) {
  /** @type {unknown} */
  let loaded;
  try {
    loaded = load(name);
  } catch (error) {
    if (isPackageNotFound(error, name)) {
      throw new Error(
        `@forthtilliath/eslint-config: the \`${option}\` option needs ${name}, ` +
          `which isn't installed. Install it as a devDependency ` +
          `(npm install --save-dev ${name}), or pass \`${option}: false\`.`,
        { cause: error },
      );
    }
    throw error;
  }
  return isModuleNamespace(loaded) ? loaded.default : loaded;
}

/**
 * `require()` of an ES module returns its namespace object, where `import()`'s
 * `.default` is the plugin; a CommonJS module is returned as `module.exports`,
 * which is already what `import()` puts in `.default`.
 *
 * @param {unknown} value
 * @returns {value is { default: unknown }}
 */
function isModuleNamespace(value) {
  return (
    typeof value === "object" &&
    value !== null &&
    Object.prototype.toString.call(value) === "[object Module]"
  );
}

/**
 * @param {unknown} error
 * @param {string} name
 * @returns {boolean}
 */
function isPackageNotFound(error, name) {
  return (
    error instanceof Error &&
    "code" in error &&
    (error.code === "MODULE_NOT_FOUND" ||
      error.code === "ERR_MODULE_NOT_FOUND") &&
    // Node names the package it couldn't find on the first line (the
    // require stack follows): checking it tells "the plugin isn't installed"
    // apart from "the plugin is installed but one of its own dependencies is
    // missing", which must not be swallowed.
    (error.message.split("\n")[0] ?? "").includes(`'${name}'`)
  );
}
