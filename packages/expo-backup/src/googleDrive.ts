/**
 * Minimal Google Drive v3 REST client, limited to the app's hidden
 * `appDataFolder` (scope `drive.appdata`): the app can't see or touch any
 * other file of the user's Drive, and the folder doesn't clutter it (only
 * visible in Drive ▸ Settings ▸ Manage apps).
 */

export const DRIVE_APPDATA_SCOPE =
  "https://www.googleapis.com/auth/drive.appdata";

const FILES_URL = "https://www.googleapis.com/drive/v3/files";
const UPLOAD_URL = "https://www.googleapis.com/upload/drive/v3/files";

export class DriveError extends Error {
  constructor(
    message: string,
    readonly status: number,
    /** Detailed reason given by Google (e.g. "accessNotConfigured"), if any. */
    readonly reason: string | null = null,
  ) {
    super(message);
    this.name = "DriveError";
  }
}

export interface DriveFile {
  id: string;
  modifiedTime: string;
}

async function readErrorReason(response: Response): Promise<string | null> {
  try {
    const data = (await response.json()) as {
      error?: { errors?: { reason?: string }[] };
    };
    return data.error?.errors?.[0]?.reason ?? null;
  } catch {
    return null;
  }
}

async function driveFetch(
  url: string,
  token: string,
  init: RequestInit = {},
): Promise<Response> {
  const headers = new Headers(init.headers);
  headers.set("Authorization", `Bearer ${token}`);
  const response = await fetch(url, { ...init, headers });
  if (!response.ok) {
    const reason = await readErrorReason(response);
    throw new DriveError(
      `Google Drive responded ${response.status}${reason ? ` (${reason})` : ""}.`,
      response.status,
      reason,
    );
  }
  return response;
}

/** Names are always generated by this package (`<appId>-backup.json`…), never user input. */
function assertSafeName(name: string) {
  if (!/^[\w.-]+$/.test(name))
    throw new Error(`Unsafe Drive file name: ${name}`);
}

/** Most recently modified file named `name` in the app folder, or null. */
export async function findAppDataFile(
  token: string,
  name: string,
): Promise<DriveFile | null> {
  assertSafeName(name);
  const params = new URLSearchParams({
    spaces: "appDataFolder",
    q: `name = '${name}' and trashed = false`,
    fields: "files(id, modifiedTime)",
    orderBy: "modifiedTime desc",
    pageSize: "1",
  });
  const response = await driveFetch(`${FILES_URL}?${params.toString()}`, token);
  const data = (await response.json()) as { files?: DriveFile[] };
  return data.files?.[0] ?? null;
}

export async function downloadAppDataFile(
  token: string,
  fileId: string,
): Promise<string> {
  const response = await driveFetch(
    `${FILES_URL}/${encodeURIComponent(fileId)}?alt=media`,
    token,
  );
  return response.text();
}

/**
 * Writes `content` to the app folder: updates `fileId` in place when given,
 * otherwise creates `name` (multipart upload: metadata + content in one
 * request).
 */
export async function uploadAppDataFile(
  token: string,
  name: string,
  content: string,
  fileId: string | null,
): Promise<DriveFile> {
  assertSafeName(name);
  const fields = "fields=id,modifiedTime";

  if (fileId) {
    const response = await driveFetch(
      `${UPLOAD_URL}/${encodeURIComponent(fileId)}?uploadType=media&${fields}`,
      token,
      {
        method: "PATCH",
        headers: { "Content-Type": "application/json" },
        body: content,
      },
    );
    return (await response.json()) as DriveFile;
  }

  const boundary = `forthtilliath-backup-${Date.now().toString()}`;
  const metadata = { name, parents: ["appDataFolder"] };
  const body = [
    `--${boundary}`,
    "Content-Type: application/json; charset=UTF-8",
    "",
    JSON.stringify(metadata),
    `--${boundary}`,
    "Content-Type: application/json",
    "",
    content,
    `--${boundary}--`,
  ].join("\r\n");

  const response = await driveFetch(
    `${UPLOAD_URL}?uploadType=multipart&${fields}`,
    token,
    {
      method: "POST",
      headers: { "Content-Type": `multipart/related; boundary=${boundary}` },
      body,
    },
  );
  return (await response.json()) as DriveFile;
}
