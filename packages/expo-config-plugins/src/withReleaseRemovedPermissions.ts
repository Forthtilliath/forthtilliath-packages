import { type ConfigPlugin, withDangerousMod } from "expo/config-plugins";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

import {
  buildReleaseRemovedPermissionsManifest,
  type ReleaseRemovedPermissionsOptions,
} from "./transforms.js";

const GENERATED_MARK = "withReleaseRemovedPermissions";

async function readIfExists(path: string): Promise<string | null> {
  try {
    return await readFile(path, "utf8");
  } catch {
    return null;
  }
}

/**
 * Strips permissions from the **release** APK only — `INTERNET` by default:
 * for an app that works fully offline, Android itself then guarantees that
 * no data can leave the phone, whatever a dependency tries. Debug builds
 * keep them (Metro needs the network).
 *
 * Writes `android/app/src/release/AndroidManifest.xml`; refuses to overwrite
 * one it didn't generate.
 *
 * `"@forthtilliath/expo-config-plugins/withReleaseRemovedPermissions"`, or
 * `["@forthtilliath/expo-config-plugins/withReleaseRemovedPermissions", { "permissions": ["INTERNET", "ACCESS_NETWORK_STATE"] }]`
 */
const withReleaseRemovedPermissions: ConfigPlugin<
  ReleaseRemovedPermissionsOptions | undefined
> = (config, options) =>
  withDangerousMod(config, [
    "android",
    async (mod) => {
      // Built first: invalid options fail the prebuild before any write.
      const manifest = buildReleaseRemovedPermissionsManifest(
        options?.permissions,
      );
      const dir = join(mod.modRequest.platformProjectRoot, "app/src/release");
      const path = join(dir, "AndroidManifest.xml");
      const existing = await readIfExists(path);
      if (existing !== null && !existing.includes(GENERATED_MARK)) {
        throw new Error(
          `withReleaseRemovedPermissions: ${path} already exists and wasn't generated by this plugin`,
        );
      }
      await mkdir(dir, { recursive: true });
      await writeFile(path, manifest);
      return mod;
    },
  ]);

export = withReleaseRemovedPermissions;
